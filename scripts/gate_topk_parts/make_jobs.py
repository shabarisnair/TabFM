#!/usr/bin/env python
"""Write the top-k gating ablation (run_gate_topk_sweep.sh) as one script per GPU.

The grid: gas-drift, url_unique, students_dropout x R in {10, 20}% x surrogate (--stes)
x initial score spread (--init-stds) x lr (--lrs) x restart seed (--init-seeds); every
run V = 500 (100 held out), validation seed 0, 300 updates.

The runs are dealt to the parts longest first, each to the part with the least
estimated work so far. Minutes per run are the means measured on the V = 500 holdout
soft-gate runs (gas-drift 27.5, url_unique 13.6, students_dropout 3.3), plus ~0.5 min
of start-up; the top-k gate costs the same per update.

Writes <name>/jobs.txt (lines "<part> <dataset> <R> <ste> <init_std> <lr> <init_seed>",
read by run_gate_topk_sweep.sh through JOBS_FILE) and <name>/run_part<k>.sh.

    python scripts/gate_topk_parts/make_jobs.py --name round1 --parts 7
    python scripts/gate_topk_parts/make_jobs.py --name hpo_remote1 --parts 5 \
        --runs-file scripts/gate_topk_parts/hpo/remote1_runs.txt

--runs-file takes an explicit run list instead of the grid flags, one run per line:
"<dataset> <R> <ste> <init_std> <lr> <init_seed>" (# comments and blank lines skipped).
"""
from __future__ import annotations

import argparse
import heapq
from pathlib import Path

HERE = Path(__file__).resolve().parent
MINUTES = {"gas-drift": 28.0, "url_unique": 14.1, "students_dropout": 3.8}


def deal(runs: list[tuple], n_parts: int) -> list[list[tuple]]:
    """Longest first, each to the least-loaded part; ties to the lower part number."""
    parts: list[list[tuple]] = [[] for _ in range(n_parts)]
    heap = [(0.0, k) for k in range(n_parts)]
    for run in sorted(runs, key=lambda x: (-MINUTES[x[0]], x)):
        load, k = heapq.heappop(heap)
        parts[k].append(run)
        heapq.heappush(heap, (load + MINUTES[run[0]], k))
    return parts


SCRIPT = """#!/usr/bin/env bash
# Top-k gating ablation, {name}, part {k} of {n}: this part's runs of
# scripts/run_gate_topk_sweep.sh (the experiment is described there), one after another
# on ONE GPU. Start the {n} parts together, one per GPU; between them they cover the
# {total} runs of {name}/jobs.txt once.
#
#     bash scripts/gate_topk_parts/{name}/run_part{k}.sh [gpu]      (default GPU {gpu})
#
# Under a scheduler that sets CUDA_VISIBLE_DEVICES to one GPU, pass 0. Any other setting
# of the sweep can be overridden through the environment or .env as usual.
#
# Runs (V = 500, 100 held out; 300 updates; L-inf step), ~{minutes:.0f} min estimated:
{listing}
# Generated by gate_topk_parts/make_jobs.py.
GPU=${{1:-{gpu}}}
HERE=$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)
export JOBS_FILE="$HERE/jobs.txt" PART={k} GPUS="$GPU"
exec bash "$HERE/../../run_gate_topk_sweep.sh"
"""


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="folder for the run list and scripts, e.g. round1")
    ap.add_argument("--parts", type=int, required=True, help="number of scripts (GPUs)")
    ap.add_argument("--datasets", nargs="+", default=list(MINUTES))
    ap.add_argument("--row-percents", type=int, nargs="+", default=[10, 20])
    ap.add_argument("--stes", nargs="+", default=["identity", "sigmoid"])
    ap.add_argument("--init-stds", nargs="+", default=["1", "0.01"])
    ap.add_argument("--lrs", nargs="+", default=["0.05", "0.2", "1"])
    ap.add_argument("--init-seeds", type=int, nargs="+", default=[0, 1, 2, 3])
    ap.add_argument("--runs-file", type=Path, default=None, help="explicit run list instead of the grid")
    a = ap.parse_args(argv)

    if a.runs_file:
        runs = []
        for line in a.runs_file.read_text().splitlines():
            if line.strip() and not line.lstrip().startswith("#"):
                ds, r, ste, std, lr, seed = line.split()
                runs.append((ds, int(r), ste, std, lr, int(seed)))
    else:
        runs = [(ds, r, ste, std, lr, seed) for ds in a.datasets for r in a.row_percents for ste in a.stes
                for std in a.init_stds for lr in a.lrs for seed in a.init_seeds]
    if len(set(runs)) != len(runs):
        raise SystemExit("the run list has duplicates")
    out = HERE / a.name
    out.mkdir(exist_ok=True)
    for old in out.glob("run_part*.sh"):  # a rerun with fewer parts must not leave strays
        old.unlink()
    parts = deal(runs, a.parts)
    lines = [f"# {a.name} of the top-k gating ablation, written by make_jobs.py.",
             "# <part> <dataset> <R> <ste> <init_std> <lr> <init_seed>"]
    for k, part in enumerate(parts, 1):
        minutes = sum(MINUTES[run[0]] for run in part)
        lines.append(f"# part {k}: {len(part)} runs, ~{minutes:.0f} min")
        lines += [f"{k} " + " ".join(map(str, run)) for run in part]
        listing = "\n".join(f"#     {ds:<16s} R={r}%  {ste:<16s} std {std:<5s} lr {lr:<5s} init {seed}"
                            for ds, r, ste, std, lr, seed in part)
        path = out / f"run_part{k}.sh"
        path.write_text(SCRIPT.format(name=a.name, k=k, n=a.parts, total=len(runs), gpu=k - 1,
                                      minutes=minutes, listing=listing))
        path.chmod(0o755)
    (out / "jobs.txt").write_text("\n".join(lines) + "\n")
    loads = [sum(MINUTES[run[0]] for run in p) for p in parts]
    print(f"{a.name}: {len(runs)} runs in {a.parts} parts; estimated minutes per part: "
          + " ".join(f"{m:.0f}" for m in loads))


if __name__ == "__main__":
    main()
