#!/usr/bin/env bash
# Generalisation of the best top-k configuration, gen, part 8 of 12: this part's
# draws of scripts/run_gate_topk_gen_sweep.sh (the experiment is described there), each
# as 4 restarts and their vote, one after another on ONE GPU. Start the 12 parts
# together, one per GPU; between them they cover the 25 draws of gen/jobs.txt once.
#
#     bash scripts/gate_topk_parts/gen/run_part8.sh [gpu]      (default GPU 7)
#
# Under a scheduler that sets CUDA_VISIBLE_DEVICES to one GPU, pass 0. Any other setting
# of the sweep can be overridden through the environment or .env as usual.
#
# Draws (dataset, R, V, validation seed; 20% of V held out), ~97 min estimated:
#     url_unique       R=20%  V=200  seed 0
#     students_dropout R=20%  V=200  seed 0
#     credit-approval  R=20%  V=100  seed 0
# Generated by gate_topk_parts/make_gen_jobs.py.
GPU=${1:-7}
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
export JOBS_FILE="$HERE/jobs.txt" PART=8 GPUS="$GPU"
exec bash "$HERE/../../run_gate_topk_gen_sweep.sh"
