#!/usr/bin/env python
"""Write the generalisation sweep of the best top-k configuration
(run_gate_topk_gen_sweep.sh) as one script per GPU.

The draws are those of the soft-gate experiment (holdout strategy): gas-drift,
url_unique, heloc, students_dropout x V in {50, 100, 200, 300, 400, 500}, and
credit-approval x V in {50, 100, 200}; validation seed 0 (--val-seeds for more); R = 20%
(--row-percents 10 20 for both). One job is one draw: its 4 restarts and their vote, all on one GPU.

The draws are dealt one validation seed at a time: within a seed, longest first, each to
the part with the least estimated work so far (carried over from the earlier seeds), so
with several seeds every part finishes one seed before it starts the next. Minutes per run
are the soft-gate runs' (scripts/gate_valsplit_parts/make_jobs.py) times 1.2, for the
extra no-gradient forward pass per update at the relaxed point, which matches the night
runs (gas-drift ~33, url_unique ~16 min), plus ~1 min per vote.

--skip-done ROOT leaves out every draw whose vote (vote.json) already exists under ROOT,
so finished draws are not run again on a machine that lacks their results.

Writes <name>/jobs.txt (lines "<part> <dataset> <R> <V> <seed>", read by
run_gate_topk_gen_sweep.sh through JOBS_FILE) and <name>/run_part<k>.sh.

    python scripts/gate_topk_parts/make_gen_jobs.py --name gen --parts 12 --skip-done results/gate_topk_gen
"""
from __future__ import annotations

import argparse
import heapq
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUN_MINUTES = {"gas-drift": 34.0, "url_unique": 17.0, "heloc": 8.0, "students_dropout": 5.0,
               "credit-approval": 1.5}
VOTE_MINUTES = 1.0
SIZES = (50, 100, 200, 300, 400, 500)
MAX_V = {"credit-approval": 200}


def vote_dir(root: Path, draw: tuple, restarts: int) -> Path:
    """Where run_gate_topk_gen_sweep.sh (vote_name, with its default settings) puts the vote."""
    ds, r, v, s = draw
    return (root / ds / f"hub-flip-local_r{r:03d}"
            / f"gate-topk-vote{restarts}_{ds}_hub-flip-local_R{r}_V{v}s{s}_H20_identity_std1_lr5_probe0.05_it300")


def draw_minutes(draw: tuple, restarts: int) -> float:
    return restarts * RUN_MINUTES[draw[0]] + VOTE_MINUTES


def deal(draws: list[tuple], n_parts: int, restarts: int) -> list[list[tuple]]:
    """One validation seed at a time; within it, longest first, each to the least-loaded
    part (ties to the lower part number). Loads carry over from seed to seed."""
    parts: list[list[tuple]] = [[] for _ in range(n_parts)]
    heap = [(0.0, k) for k in range(n_parts)]
    for seed in sorted({d[3] for d in draws}):
        batch = [d for d in draws if d[3] == seed]
        for draw in sorted(batch, key=lambda d: (-draw_minutes(d, restarts), d)):
            load, k = heapq.heappop(heap)
            parts[k].append(draw)
            heapq.heappush(heap, (load + draw_minutes(draw, restarts), k))
    return parts


SCRIPT = """#!/usr/bin/env bash
# Generalisation of the best top-k configuration, {name}, part {k} of {n}: this part's
# draws of scripts/run_gate_topk_gen_sweep.sh (the experiment is described there), each
# as {restarts} restarts and their vote, one after another on ONE GPU. Start the {n} parts
# together, one per GPU; between them they cover the {total} draws of {name}/jobs.txt once.
#
#     bash scripts/gate_topk_parts/{name}/run_part{k}.sh [gpu]      (default GPU {gpu})
#
# Under a scheduler that sets CUDA_VISIBLE_DEVICES to one GPU, pass 0. Any other setting
# of the sweep can be overridden through the environment or .env as usual.
#
# Draws (dataset, R, V, validation seed; 20% of V held out), ~{minutes:.0f} min estimated:
{listing}
# Generated by gate_topk_parts/make_gen_jobs.py.
GPU=${{1:-{gpu}}}
HERE=$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)
export JOBS_FILE="$HERE/jobs.txt" PART={k} GPUS="$GPU"
exec bash "$HERE/../../run_gate_topk_gen_sweep.sh"
"""


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="folder for the draw list and scripts, e.g. gen_r10")
    ap.add_argument("--parts", type=int, required=True, help="number of scripts (GPUs)")
    ap.add_argument("--datasets", nargs="+", default=list(RUN_MINUTES))
    ap.add_argument("--row-percents", type=int, nargs="+", default=[20])
    ap.add_argument("--val-sizes", type=int, nargs="+", default=list(SIZES))
    ap.add_argument("--val-seeds", type=int, nargs="+", default=[0])
    ap.add_argument("--restarts", type=int, default=4, help="restarts per draw (INIT_SEEDS of the sweep)")
    ap.add_argument("--skip-done", type=Path, default=None, metavar="ROOT",
                    help="leave out the draws whose vote.json exists under ROOT (e.g. results/gate_topk_gen)")
    a = ap.parse_args(argv)

    draws = [(ds, r, v, s) for ds in a.datasets for r in a.row_percents for v in a.val_sizes
             if v <= MAX_V.get(ds, 10**9) for s in a.val_seeds]
    done = [d for d in draws if a.skip_done and (vote_dir(a.skip_done, d, a.restarts) / "vote.json").exists()]
    draws = [d for d in draws if d not in done]
    for d in done:
        print(f"already done, left out: {d[0]} R={d[1]}% V={d[2]} seed {d[3]}")
    out = HERE / a.name
    out.mkdir(exist_ok=True)
    for old in out.glob("run_part*.sh"):  # a rerun with fewer parts must not leave strays
        old.unlink()
    parts = deal(draws, a.parts, a.restarts)
    lines = [f"# {a.name}: the best top-k configuration on the soft-gate draws, written by make_gen_jobs.py.",
             "# <part> <dataset> <R> <V> <seed>   (one draw = the restarts and their vote)"]
    lines += [f"# already done, left out: {ds} {r} {v} {s}" for ds, r, v, s in done]
    loads = []
    for k, part in enumerate(parts, 1):
        minutes = sum(draw_minutes(d, a.restarts) for d in part)
        loads.append(minutes)
        lines.append(f"# part {k}: {len(part)} draws, ~{minutes:.0f} min")
        lines += [f"{k} " + " ".join(map(str, d)) for d in part]
        listing = "\n".join(f"#     {ds:<16s} R={r}%  V={v:<4d} seed {s}" for ds, r, v, s in part)
        path = out / f"run_part{k}.sh"
        path.write_text(SCRIPT.format(name=a.name, k=k, n=a.parts, total=len(draws), restarts=a.restarts,
                                      gpu=k - 1, minutes=minutes, listing=listing))
        path.chmod(0o755)
    (out / "jobs.txt").write_text("\n".join(lines) + "\n")
    print(f"{a.name}: {len(draws)} draws ({len(draws) * a.restarts} runs) in {a.parts} parts; "
          f"estimated minutes per part: " + " ".join(f"{m:.0f}" for m in loads))


if __name__ == "__main__":
    main()
