#!/usr/bin/env python
"""Write round 2 of the gate-valsplit sweep: the run list and one script per GPU.

Round 2 adds, to the 20 runs of round 1 (gas-drift and url_unique, all validation rows
fitted, V = 100..500):
  - V = 50 with all validation rows fitted (strategy "full"), for gas-drift and url_unique;
  - the validation-test holdout (strategy "holdout", 20% of the V rows held out to choose
    the iteration), V = 50..500, for gas-drift and url_unique;
  - both strategies, V = 50..500, for the balanced binary datasets heloc and
    credit-approval. credit-approval's whole training split is 457 rows, so it stops at
    V = 200, which keeps its context at least as large as the validation set;
  - both strategies, V = 50..500, for students_dropout (3 classes, 50/32/18%, a
    3000-row context).
All at R = 10 and 20, validation seed 0.

The runs are dealt to N_PARTS parts longest first, each to the part with the least
estimated work so far (LPT). Estimated minutes per run come from the finished runs
(gas-drift 27, url_unique 13 on the GPU server) and short timing runs here (heloc
~5.5, students_dropout ~3.3, credit-approval ~0.3), plus ~0.5 min of start-up each.

Writes round2_jobs.txt (lines "<part> <dataset> <R> <V> <seed> <strategy>", read by
run_gate_valsplit_sweep.sh through JOBS_FILE) and run_part<k>.sh next to this file.

    python scripts/gate_valsplit_parts/make_round2_jobs.py
"""
from __future__ import annotations

import heapq
from pathlib import Path

HERE = Path(__file__).resolve().parent
N_PARTS = 11
MINUTES = {"gas-drift": 27.5, "url_unique": 13.5, "heloc": 6.0, "students_dropout": 3.8,
           "credit-approval": 1.0}
SIZES = (50, 100, 200, 300, 400, 500)


def round2_runs() -> list[tuple]:
    runs = []
    for ds in ("gas-drift", "url_unique", "heloc", "students_dropout", "credit-approval"):
        sizes = [v for v in SIZES if ds != "credit-approval" or v <= 200]
        for r in (10, 20):
            for v in sizes:
                for strategy in ("full", "holdout"):
                    if ds in ("gas-drift", "url_unique") and strategy == "full" and v >= 100:
                        continue  # round 1
                    runs.append((ds, r, v, 0, strategy))
    return runs


def deal(runs: list[tuple], n_parts: int) -> list[list[tuple]]:
    """Longest first, each to the least-loaded part; ties to the lower part number."""
    parts: list[list[tuple]] = [[] for _ in range(n_parts)]
    heap = [(0.0, k) for k in range(n_parts)]
    for run in sorted(runs, key=lambda x: (-MINUTES[x[0]], x)):
        load, k = heapq.heappop(heap)
        parts[k].append(run)
        heapq.heappush(heap, (load + MINUTES[run[0]], k))
    return parts


SCRIPT = """#!/usr/bin/env bash
# Gate-valsplit sweep, round 2, part {k} of {n}: this part's runs of
# scripts/run_gate_valsplit_sweep.sh (the experiment is described there), one after
# another on ONE GPU. Start the {n} parts together, one per GPU; between them they cover
# the {total} runs of round 2 (gate_valsplit_parts/round2_jobs.txt) once.
#
#     bash scripts/gate_valsplit_parts/run_part{k}.sh [gpu]      (default GPU {gpu})
#
# Under a scheduler that sets CUDA_VISIBLE_DEVICES to one GPU, pass 0. Any other setting
# of the sweep can be overridden through the environment or .env as usual, e.g.
#     WANDB_MODE=offline bash scripts/gate_valsplit_parts/run_part{k}.sh 3
#
# Runs (hub-flip-local; PGD, L-inf step, lr 0.05, 300 updates; validation seed 0;
# holdout = 20% of the V rows held out to choose the iteration), ~{minutes:.0f} min estimated:
{listing}
# Generated by make_round2_jobs.py.
GPU=${{1:-{gpu}}}
HERE=$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)
export JOBS_FILE="$HERE/round2_jobs.txt" PART={k} GPUS="$GPU"
exec bash "$HERE/../run_gate_valsplit_sweep.sh"
"""


def main() -> None:
    runs = round2_runs()
    parts = deal(runs, N_PARTS)
    lines = ["# Round 2 of the gate-valsplit sweep, written by make_round2_jobs.py.",
             "# <part> <dataset> <R> <V> <seed> <strategy>   (strategy: full | holdout)"]
    for k, part in enumerate(parts, 1):
        minutes = sum(MINUTES[run[0]] for run in part)
        lines.append(f"# part {k}: {len(part)} runs, ~{minutes:.0f} min")
        lines += [f"{k} {ds} {r} {v} {s} {strategy}" for ds, r, v, s, strategy in part]
        listing = "\n".join(f"#     {ds:<16s} R={r}%  V={v:<4d} {strategy}" for ds, r, v, s, strategy in part)
        path = HERE / f"run_part{k}.sh"
        path.write_text(SCRIPT.format(k=k, n=N_PARTS, total=len(runs), gpu=k - 1, minutes=minutes,
                                      listing=listing))
        path.chmod(0o755)
    (HERE / "round2_jobs.txt").write_text("\n".join(lines) + "\n")
    loads = [sum(MINUTES[run[0]] for run in p) for p in parts]
    print(f"{len(runs)} runs in {N_PARTS} parts; estimated minutes per part: "
          + " ".join(f"{m:.0f}" for m in loads))


if __name__ == "__main__":
    main()
