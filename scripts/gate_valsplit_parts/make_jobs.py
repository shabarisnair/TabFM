#!/usr/bin/env python
"""Write a round of the gate-valsplit sweep for given validation seeds: the run list and
one script per GPU, in their own folder next to this file.

Every configuration of the sweep is included once per seed:
    gas-drift, url_unique, heloc, students_dropout   V = 50, 100, 200, 300, 400, 500
    credit-approval                                    V = 50, 100, 200 (457-row training split)
    x R = 10, 20  x  strategy full (all V rows fitted) | holdout (20% held out to choose
    the iteration)
= 108 runs per seed. Seed 0 is rounds 1 and 2 (make_round2_jobs.py); other seeds draw
other validation sets (and so other contexts, other held-out rows and other poisoned rows).

The runs are dealt to the parts longest first, each to the part with the least
estimated work so far. Minutes per run are the means measured on the seed-0 runs, plus
~0.5 min of start-up.

Writes <name>/jobs.txt (lines "<part> <dataset> <R> <V> <seed> <strategy>", read by
run_gate_valsplit_sweep.sh through JOBS_FILE) and <name>/run_part<k>.sh.

    python scripts/gate_valsplit_parts/make_jobs.py --name round3 --seeds 1 2 --parts 7
"""
from __future__ import annotations

import argparse
import heapq
from pathlib import Path

HERE = Path(__file__).resolve().parent
MINUTES = {"gas-drift": 27.9, "url_unique": 13.8, "heloc": 6.3, "students_dropout": 3.9,
           "credit-approval": 0.8}
DATASETS = ("gas-drift", "url_unique", "heloc", "students_dropout", "credit-approval")
SIZES = (50, 100, 200, 300, 400, 500)
MAX_V = {"credit-approval": 200}


def runs_for(seeds) -> list[tuple]:
    return [(ds, r, v, s, strategy)
            for s in seeds for ds in DATASETS for r in (10, 20)
            for v in SIZES if v <= MAX_V.get(ds, v)
            for strategy in ("full", "holdout")]


def deal(runs: list[tuple], n_parts: int) -> list[list[tuple]]:
    """Longest first, each to the least-loaded part; ties to the lower part number."""
    parts: list[list[tuple]] = [[] for _ in range(n_parts)]
    heap = [(0.0, k) for k in range(n_parts)]
    for run in sorted(runs, key=lambda x: (-MINUTES[x[0]], x)):
        load, k = heapq.heappop(heap)
        parts[k].append(run)
        heapq.heappush(heap, (load + MINUTES[run[0]], k))
    return parts


SCRIPT = """#!/usr/bin/env bash
# Gate-valsplit sweep, {name} (validation seeds {seeds}), part {k} of {n}: this part's
# runs of scripts/run_gate_valsplit_sweep.sh (the experiment is described there), one
# after another on ONE GPU. Start the {n} parts together, one per GPU; between them they
# cover the {total} runs of {name}/jobs.txt once.
#
#     bash scripts/gate_valsplit_parts/{name}/run_part{k}.sh [gpu]      (default GPU {gpu})
#
# Under a scheduler that sets CUDA_VISIBLE_DEVICES to one GPU, pass 0. Any other setting
# of the sweep can be overridden through the environment or .env as usual, e.g.
#     WANDB_MODE=offline bash scripts/gate_valsplit_parts/{name}/run_part{k}.sh 3
#
# Runs (hub-flip-local; PGD, L-inf step, lr 0.05, 300 updates; holdout = 20% of the V
# rows held out to choose the iteration), ~{minutes:.0f} min estimated:
{listing}
# Generated by gate_valsplit_parts/make_jobs.py.
GPU=${{1:-{gpu}}}
HERE=$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)
export JOBS_FILE="$HERE/jobs.txt" PART={k} GPUS="$GPU"
exec bash "$HERE/../../run_gate_valsplit_sweep.sh"
"""


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="folder for the run list and scripts, e.g. round3")
    ap.add_argument("--seeds", type=int, nargs="+", required=True, help="validation seeds")
    ap.add_argument("--parts", type=int, required=True, help="number of scripts (GPUs)")
    a = ap.parse_args(argv)

    out = HERE / a.name
    out.mkdir(exist_ok=True)
    for old in out.glob("run_part*.sh"):  # a rerun with fewer parts must not leave strays
        old.unlink()
    runs = runs_for(a.seeds)
    parts = deal(runs, a.parts)
    seeds = " ".join(map(str, a.seeds))
    lines = [f"# {a.name} of the gate-valsplit sweep (validation seeds {seeds}), written by make_jobs.py.",
             "# <part> <dataset> <R> <V> <seed> <strategy>   (strategy: full | holdout)"]
    for k, part in enumerate(parts, 1):
        minutes = sum(MINUTES[run[0]] for run in part)
        lines.append(f"# part {k}: {len(part)} runs, ~{minutes:.0f} min")
        lines += [f"{k} {ds} {r} {v} {s} {strategy}" for ds, r, v, s, strategy in part]
        listing = "\n".join(f"#     {ds:<16s} R={r}%  V={v:<4d} seed {s}  {strategy}"
                            for ds, r, v, s, strategy in part)
        path = out / f"run_part{k}.sh"
        path.write_text(SCRIPT.format(name=a.name, seeds=seeds, k=k, n=a.parts, total=len(runs),
                                      gpu=k - 1, minutes=minutes, listing=listing))
        path.chmod(0o755)
    (out / "jobs.txt").write_text("\n".join(lines) + "\n")
    loads = [sum(MINUTES[run[0]] for run in p) for p in parts]
    print(f"{a.name}: {len(runs)} runs in {a.parts} parts; estimated minutes per part: "
          + " ".join(f"{m:.0f}" for m in loads))


if __name__ == "__main__":
    main()
